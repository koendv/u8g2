# Generate the display table and font subset of a board, from the board's
# displays.txt and fonts.txt. Run by micropython.cmake and micropython.mk
# when the build is configured; files are only written when they change.
#
# Writes, in the output directory:
#   u8g2_displays_table.h  D(...) per display, from codebuild -t
#   u8g2_fonts_table.h     FONT(...) per font, and U8G2_MP_DEFAULT_FONT
#   u8g2_fonts_data.h      font arrays, from csrc/u8g2_fonts.c
#   codebuild              the u8g2 code generator, built with the host compiler
#
# usage: gen_u8g2.py --cc <host cc> --config <board dir> --out <dir>
#        gen_u8g2.py --cc <host cc> --list     (setup names for displays.txt)

import argparse
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
u8g2_dir = os.path.abspath(os.path.join(here, "..", "..", "..", ".."))
codebuild_c = os.path.join(u8g2_dir, "tools", "codebuild", "codebuild.c")
fonts_c = os.path.join(u8g2_dir, "csrc", "u8g2_fonts.c")


def fail(msg):
    sys.exit("u8g2: " + msg)


def read_names(path):
    if not os.path.isfile(path):
        fail("%s not found. Each board needs a displays.txt and a fonts.txt, "
             "see sys/micropython/README.md" % path)
    names = []
    with open(path) as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                names.append(line)
    if not names:
        fail("%s is empty" % path)
    return names


def write_if_changed(path, text):
    try:
        with open(path, encoding="latin-1") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(path + ".tmp", "w", encoding="latin-1") as f:
        f.write(text)
    os.replace(path + ".tmp", path)


# build codebuild with the host compiler, not the cross compiler of the port
def build_codebuild(cc, outdir):
    exe = os.path.join(outdir, "codebuild.exe" if os.name == "nt" else "codebuild")
    if os.path.isfile(exe) and os.path.getmtime(exe) >= os.path.getmtime(codebuild_c):
        return exe
    cmd = shlex.split(cc) + ["-o", exe, codebuild_c]
    # the esp-idf environment puts toolchain directories with an unprefixed 'as' and 'ld'
    # in PATH. Look for the assembler and linker next to the host compiler first.
    env = dict(os.environ)
    cc_path = shutil.which(cmd[0])
    if cc_path:
        env["PATH"] = os.path.dirname(cc_path) + os.pathsep + env.get("PATH", "")
    try:
        r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=env)
    except OSError as e:
        fail("host compiler '%s': %s. Set U8G2_HOST_CC" % (cc, e))
    if r.returncode != 0:
        sys.stderr.write(r.stdout.decode(errors="replace"))
        fail("building codebuild with '%s' failed" % cc)
    return exe


def gen_displays(exe, names):
    r = subprocess.run([exe, "-t"], input="\n".join(names).encode(),
                       stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if r.returncode != 0:
        sys.stderr.write(r.stderr.decode(errors="replace"))
        fail("unknown display in displays.txt, gen_u8g2.py --list shows the names")
    return ("/* generated by tools/gen_u8g2.py from displays.txt, do not edit */\n"
            "/* D(python_name, display_cb, cad_cb, ll_hvline, tile_width, tile_height, com) */\n"
            + r.stdout.decode())


def gen_fonts(names):
    with open(fonts_c, "rb") as f:
        text = f.read().decode("latin-1")

    # each font: optional comment block, then "const uint8_t u8g2_font_NAME[N] ... = \n  "..."...;"
    pat = re.compile(
        r"(/\*\n  Fontname:.*?\*/\n)?(const uint8_t u8g2_font_(\w+)\[(\d+)\] U8G2_FONT_SECTION\(\"\w+\"\) = \n.*?;\n)",
        re.S,
    )
    fonts = {}
    for m in pat.finditer(text):
        fonts[m.group(3)] = ((m.group(1) or "") + m.group(2), int(m.group(4)))

    missing = [n for n in names if n not in fonts]
    if missing:
        fail("fonts not found in csrc/u8g2_fonts.c: " + ", ".join(missing))

    data = "/* generated by tools/gen_u8g2.py from fonts.txt and csrc/u8g2_fonts.c, do not edit */\n\n"
    data += "\n".join(fonts[n][0] for n in names)

    table = "/* generated by tools/gen_u8g2.py from fonts.txt, do not edit */\n"
    table += "/* font after init(): the first font of fonts.txt */\n"
    table += "#ifndef U8G2_MP_DEFAULT_FONT\n#define U8G2_MP_DEFAULT_FONT u8g2_font_%s\n#endif\n" % names[0]
    table += "/* FONT(python_name, c_array) */\n"
    table += "".join("FONT(font_%s, u8g2_font_%s)\n" % (n, n) for n in names)

    return table, data, sum(fonts[n][1] for n in names)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cc", default="cc", help="host c compiler")
    ap.add_argument("--config", help="directory with displays.txt and fonts.txt")
    ap.add_argument("--out", help="output directory")
    ap.add_argument("--list", action="store_true", help="list the setup names for displays.txt")
    args = ap.parse_args()

    if args.list:
        with tempfile.TemporaryDirectory() as tmp:
            sys.exit(subprocess.run([build_codebuild(args.cc, tmp), "-l"]).returncode)

    if not args.config or not args.out:
        fail("--config and --out are required")

    display_names = read_names(os.path.join(args.config, "displays.txt"))
    font_names = read_names(os.path.join(args.config, "fonts.txt"))

    os.makedirs(args.out, exist_ok=True)
    displays = gen_displays(build_codebuild(args.cc, args.out), display_names)
    fonts_table, fonts_data, font_bytes = gen_fonts(font_names)

    write_if_changed(os.path.join(args.out, "u8g2_displays_table.h"), displays)
    write_if_changed(os.path.join(args.out, "u8g2_fonts_table.h"), fonts_table)
    write_if_changed(os.path.join(args.out, "u8g2_fonts_data.h"), fonts_data)

    sys.stderr.write("u8g2: %s: %d displays, %d fonts (%d bytes)\n"
                     % (args.config, len(display_names), len(font_names), font_bytes))


main()
