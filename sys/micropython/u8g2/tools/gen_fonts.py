# Extract the fonts listed in tools/fonts.txt from csrc/u8g2_fonts.c.
#
# Writes:
#   u8g2_fonts_subset.c  font arrays
#   u8g2_fonts_table.h   module globals entries
#
# usage: gen_fonts.py   (fonts from csrc/u8g2_fonts.c of this u8g2 tree)

import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
moddir = os.path.dirname(here)
u8g2_dir = os.path.abspath(os.path.join(moddir, "..", "..", ".."))
src = os.path.join(u8g2_dir, "csrc", "u8g2_fonts.c")
out_c = os.path.join(moddir, "u8g2_fonts_subset.c")
out_h = os.path.join(moddir, "u8g2_fonts_table.h")

names = []
with open(os.path.join(here, "fonts.txt")) as f:
    for line in f:
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line)

with open(src, "rb") as f:
    text = f.read().decode("latin-1")

# each font: optional comment block, then "const uint8_t u8g2_font_NAME[N] ... = \n  "..."...;"
pat = re.compile(
    r"(/\*\n  Fontname:.*?\*/\n)?(const uint8_t u8g2_font_(\w+)\[\d+\] U8G2_FONT_SECTION\(\"\w+\"\) = \n.*?;\n)",
    re.S,
)
fonts = {}
for m in pat.finditer(text):
    fonts[m.group(3)] = (m.group(1) or "") + m.group(2)

missing = [n for n in names if n not in fonts]
if missing:
    sys.exit("fonts not found: " + ", ".join(missing))

total = 0
with open(out_c, "w", encoding="latin-1") as f:
    f.write("/* generated by tools/gen_fonts.py from u8g2 csrc/u8g2_fonts.c, do not edit */\n")
    f.write('#include "u8g2.h"\n\n')
    for n in names:
        f.write(fonts[n])
        f.write("\n")
        total += int(re.search(r"\[(\d+)\]", fonts[n].split("const uint8_t", 1)[1]).group(1))

with open(out_h, "w") as f:
    f.write("/* generated by tools/gen_fonts.py, do not edit */\n")
    f.write("/* FONT(python_name, c_array) */\n")
    for n in names:
        f.write("FONT(font_%s, u8g2_font_%s)\n" % (n, n))

print("%d fonts, %d bytes" % (len(names), total))
